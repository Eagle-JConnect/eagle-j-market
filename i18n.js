export function getLanguage(){ return localStorage.getItem("eaglej-language") || "en"; }
export function t(value){ return translations[getLanguage()]?.[value] || value; }

function translate(root=document){
  const map=translations[getLanguage()]||translations.en;
  const walker=document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const nodes=[]; let node;
  while(node=walker.nextNode()) nodes.push(node);

  for(const textNode of nodes){
    if(!textNode.nodeValue.trim() || textNode.parentElement?.closest("script,style")) continue;
    const source=textNode.dataset?.eaglejSource ?? textNode.nodeValue.trim();
    if(!textNode.dataset.eaglejSource) textNode.dataset.eaglejSource=source;
    const translated=map[source] || source;
    if(textNode.nodeValue.trim() !== translated){
      textNode.nodeValue=textNode.nodeValue.replace(textNode.nodeValue.trim(),translated);
    }
  }

  root.querySelectorAll?.("[placeholder],[title]").forEach(el=>{
    for(const attr of ["placeholder","title"]){
      if(!el.hasAttribute(attr)) continue;
      const key=el.dataset[`eaglej${attr[0].toUpperCase()+attr.slice(1)}Source`] || el.getAttribute(attr);
      if(!el.dataset[`eaglej${attr[0].toUpperCase()+attr.slice(1)}Source`]) el.dataset[`eaglej${attr[0].toUpperCase()+attr.slice(1)}Source`]=key;
      el.setAttribute(attr,map[key]||key);
    }
  });
  root.querySelectorAll?.("option").forEach(el=>{
    const key=el.dataset.eaglejSource || el.textContent.trim();
    if(!el.dataset.eaglejSource) el.dataset.eaglejSource=key;
    el.textContent=map[key]||key;
  });
  const titleKey=document.documentElement.dataset.eaglejTitleSource || document.title;
  if(!document.documentElement.dataset.eaglejTitleSource) document.documentElement.dataset.eaglejTitleSource=titleKey;
  document.title=map[titleKey]||titleKey;
  const select=document.querySelector("#languageSelect");
  if(select) select.value=getLanguage();
}

let initialized=false;
let observer=null;
export function setLanguage(lang){
  const next=translations[lang] ? lang : "en";
  localStorage.setItem("eaglej-language",next);
  translate(document);
  window.dispatchEvent(new CustomEvent("eaglej-language-change",{detail:{lang:next}}));
}
export function applyLanguage(){ translate(document); }

export function initLanguage(){
  if(initialized){ applyLanguage(); return; }
  initialized=true;
  applyLanguage();
  observer=new MutationObserver(mutations=>{
    for(const m of mutations){
      if(m.type==="childList" && (m.addedNodes?.length||0)) {
        m.addedNodes.forEach(node=>{ if(node.nodeType===1 || node.nodeType===3) translate(node.nodeType===1?node:node.parentElement); });
      }
    }
  });
  observer.observe(document.documentElement,{subtree:true,childList:true});
  window.addEventListener("eaglej-language-change",applyLanguage,{passive:true});
}
