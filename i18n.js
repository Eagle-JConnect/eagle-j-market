export function getLanguage(){ return localStorage.getItem("eaglej-language") || "en"; }
export function setLanguage(lang){ localStorage.setItem("eaglej-language", translations[lang] ? lang : "en"); applyLanguage(); window.dispatchEvent(new CustomEvent("eaglej-language-change",{detail:{lang:getLanguage()}})); }
export function t(value){ const lang=getLanguage(); return translations[lang]?.[value] || value; }

function translateNode(root=document){
  const lang=getLanguage();
  const map=translations[lang]||translations.en;
  const walker=document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const nodes=[]; let n;
  while(n=walker.nextNode()) nodes.push(n);
  for(const node of nodes){
    if(!node.nodeValue.trim() || node.parentElement?.closest("script,style")) continue;
    const original=node.nodeValue.trim();
    const translated=map[original];
    if(translated && original!==translated) node.nodeValue=node.nodeValue.replace(original,translated);
  }
  root.querySelectorAll?.("[placeholder],[title],option").forEach(el=>{
    for(const attr of ["placeholder","title"]){
      if(el.hasAttribute(attr)){ const v=el.getAttribute(attr); if(map[v]) el.setAttribute(attr,map[v]); }
    }
    if(el.tagName==="OPTION" && map[el.textContent.trim()]) el.textContent=map[el.textContent.trim()];
  });
  const title=map[document.title]; if(title) document.title=title;
}
export function applyLanguage(){ translateNode(document); const s=document.querySelector("#languageSelect"); if(s) s.value=getLanguage(); }
let languageInitialized=false;

export function initLanguage(){
  if(languageInitialized) return;
  languageInitialized=true;
  applyLanguage();
  window.addEventListener("eaglej-language-change", applyLanguage, {passive:true});
}
